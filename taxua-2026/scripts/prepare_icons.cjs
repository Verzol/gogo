/* One-off asset preparation, not a runtime build.
   Serialize official Lucide 1.23.0 icon nodes from the pinned Hue bundle.
   Never edit icon paths by hand. Add a name here when adding an interface icon. */
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname,'..');
const {icons} = require(path.join(root,'vendor/lucide-1.23.0.min.js'));
const names = ['route','users-round','backpack','camera','soup','menu','x','moon-star','sunrise','sun','sunset','clock-3','move-up-right','flag','coins','notebook-pen','plus','arrow-left','arrow-right','bus','ticket','piggy-bank','cloud','cloud-sun','cloud-fog','cloud-drizzle','cloud-rain','cloud-snow','cloud-lightning','wind','pause','play','map','map-pin','house','coffee','waves','mountain','scan','chevron-up','chevron-right','dices','rotate-ccw','shuffle','eye','sliders-horizontal','lock-keyhole','check','sparkles','maximize','minimize','list','chevron-down','refresh-cw','book-x','log-out'];
const escape = value => String(value).replace(/&/g,'&amp;').replace(/"/g,'&quot;').replace(/</g,'&lt;');
const symbols = names.map(name => {
  const key = name.split('-').map(word=>word[0].toUpperCase()+word.slice(1)).join('');
  if (!icons[key]) throw new Error('Missing official icon: '+name);
  const nodes = icons[key].map(([tag,attrs])=>`<${tag} ${Object.entries(attrs).map(([key,value])=>`${key}="${escape(value)}"`).join(' ')} />`).join('');
  return `<symbol id="trip-${name}" viewBox="0 0 24 24">${nodes}</symbol>`;
}).join('\n');
const start = '  <!-- Lucide sprite: generated by scripts/prepare_icons.cjs -->';
const end = '  <!-- End Lucide sprite -->';
const p = path.join(root,'index.html');
let html = fs.readFileSync(p,'utf8');
const sprite = start+'\n  <svg xmlns="http://www.w3.org/2000/svg" class="icon-definitions" aria-hidden="true"><defs>\n'+symbols+'\n  </defs></svg>\n'+end;
if(html.includes(start)) html = html.slice(0,html.indexOf(start))+sprite+html.slice(html.indexOf(end)+end.length);
else html = html.replace('  <div id="scenery"',sprite+'\n  <div id="scenery"');
fs.writeFileSync(p,html);
console.log('Prepared '+names.length+' official Lucide symbols.');
